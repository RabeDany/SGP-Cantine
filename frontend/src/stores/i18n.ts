function getMessage(lang: SupportedLang, key: string): string {
  const message = translations[lang][key]
  if (message !== undefined) return message
  return translations.fr[key] ?? key
}

export const useI18nStore = defineStore('i18n', () => {
  const language = ref<SupportedLang>(loadFromStorage(STORAGE_KEY, 'fr'))

  function setLanguage(lang: SupportedLang) {
    language.value = lang
    saveToStorage(STORAGE_KEY, lang)
    document.documentElement.lang = lang
  }

  const locale = computed(() => (language.value === 'mg' ? 'mg-MG' : 'fr-FR'))

  function t(key: string, params?: Record<string, string | number>) {
    let text = getMessage(language.value, key)
    if (params) {
      Object.entries(params).forEach(([param, value]) => {
        text = text.replace(`{${param}}`, String(value))
      })
    }
    return text
  }

  if (typeof document !== 'undefined') {
    document.documentElement.lang = language.value
  }

  return {
    language,
    locale,
    setLanguage,
    t,
  }
})
